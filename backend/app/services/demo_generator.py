import uuid
from datetime import datetime, timedelta
from typing import List, Dict, Any
from sqlalchemy.orm import Session
from app.models.event import SecurityEvent
from app.models.alert import Alert
from app.models.investigation import Investigation
from app.engine.detector import DetectionEngine
from app.utils.logging import logger

class DemoDataGenerator:
    """
    Generates realistic, synthetic security events and alerts for demonstration.
    ALL events and alerts generated by this module are strictly marked with:
    is_synthetic = True
    """

    @staticmethod
    def generate_demo_scenario(db: Session) -> Dict[str, Any]:
        # Purge existing synthetic data first
        DemoDataGenerator.reset_demo_data(db)

        now = datetime.utcnow()
        events: List[SecurityEvent] = []

        # Scenario 1: SSH Brute-Force against Bastion (IP 194.26.29.112 - External)
        # 12 failed attempts followed by lockout
        bf_ip = "194.26.29.112"
        for i in range(12):
            ts = now - timedelta(minutes=45) + timedelta(seconds=i * 15)
            user = "admin" if i % 2 == 0 else "support"
            ev = SecurityEvent(
                event_uuid=f"evt-demo-{uuid.uuid4().hex[:12]}",
                timestamp=ts,
                source_ip=bf_ip,
                source_port=49000 + i,
                destination_ip="10.0.0.15",
                destination_port=22,
                event_type="SSH_AUTH",
                action="LOGIN",
                status="FAILURE",
                username=user,
                hostname="bastion-eu-01",
                service="sshd",
                raw_log=f"{ts.strftime('%b %d %H:%M:%S')} bastion-eu-01 sshd[{30100+i}]: Failed password for invalid user {user} from {bf_ip} port {49000+i} ssh2",
                parser_type="SSH_AUTH",
                is_synthetic=True,
                metadata_json={"campaign": "Simulated SSH Brute-Force", "synthetic": True}
            )
            events.append(ev)

        # Scenario 2: Horizontal Password Spraying (IP 185.220.101.5 - Tor Exit)
        # Attacks 6 distinct accounts within 10 minutes
        spray_ip = "185.220.101.5"
        accounts = ["jdoe", "asmith", "finance_dept", "db_backup", "deploy", "jenkins"]
        for idx, acct in enumerate(accounts):
            ts = now - timedelta(minutes=25) + timedelta(seconds=idx * 40)
            ev = SecurityEvent(
                event_uuid=f"evt-demo-{uuid.uuid4().hex[:12]}",
                timestamp=ts,
                source_ip=spray_ip,
                source_port=51000 + idx,
                destination_ip="10.0.0.20",
                destination_port=22,
                event_type="SSH_AUTH",
                action="LOGIN",
                status="FAILURE",
                username=acct,
                hostname="auth-node-02",
                service="sshd",
                raw_log=f"{ts.strftime('%b %d %H:%M:%S')} auth-node-02 sshd[{31200+idx}]: Failed password for {acct} from {spray_ip} port {51000+idx} ssh2",
                parser_type="SSH_AUTH",
                is_synthetic=True,
                metadata_json={"campaign": "Simulated Password Spray", "synthetic": True}
            )
            events.append(ev)

        # Scenario 3: Account Takeover (Multiple failures followed by SUCCESS)
        # IP 45.142.195.88 attacks 'finance_lead' 4 times, then succeeds!
        compromise_ip = "45.142.195.88"
        for i in range(4):
            ts = now - timedelta(minutes=15) + timedelta(seconds=i * 20)
            ev = SecurityEvent(
                event_uuid=f"evt-demo-{uuid.uuid4().hex[:12]}",
                timestamp=ts,
                source_ip=compromise_ip,
                source_port=52100 + i,
                destination_ip="10.0.0.30",
                destination_port=22,
                event_type="SSH_AUTH",
                action="LOGIN",
                status="FAILURE",
                username="finance_lead",
                hostname="finance-portal",
                service="sshd",
                raw_log=f"{ts.strftime('%b %d %H:%M:%S')} finance-portal sshd[{32000+i}]: Failed password for finance_lead from {compromise_ip} port {52100+i} ssh2",
                parser_type="SSH_AUTH",
                is_synthetic=True,
                metadata_json={"campaign": "Simulated Account Takeover", "synthetic": True}
            )
            events.append(ev)

        # Now the success event!
        success_ts = now - timedelta(minutes=13)
        ev_succ = SecurityEvent(
            event_uuid=f"evt-demo-{uuid.uuid4().hex[:12]}",
            timestamp=success_ts,
            source_ip=compromise_ip,
            source_port=52120,
            destination_ip="10.0.0.30",
            destination_port=22,
            event_type="SSH_AUTH",
            action="LOGIN",
            status="SUCCESS",
            username="finance_lead",
            hostname="finance-portal",
            service="sshd",
            raw_log=f"{success_ts.strftime('%b %d %H:%M:%S')} finance-portal sshd[32010]: Accepted password for finance_lead from {compromise_ip} port 52120 ssh2",
            parser_type="SSH_AUTH",
            is_synthetic=True,
            metadata_json={"campaign": "Simulated Account Takeover", "synthetic": True}
        )
        events.append(ev_succ)

        # Scenario 4: Direct Remote Root Login from Untrusted External IP
        root_ip = "91.240.118.172"
        root_ts = now - timedelta(minutes=8)
        ev_root = SecurityEvent(
            event_uuid=f"evt-demo-{uuid.uuid4().hex[:12]}",
            timestamp=root_ts,
            source_ip=root_ip,
            source_port=44321,
            destination_ip="10.0.0.5",
            destination_port=22,
            event_type="SSH_AUTH",
            action="LOGIN",
            status="SUCCESS",
            username="root",
            hostname="core-database-01",
            service="sshd",
            raw_log=f"{root_ts.strftime('%b %d %H:%M:%S')} core-database-01 sshd[33100]: Accepted publickey for root from {root_ip} port 44321 ssh2: RSA SHA256:abc12345",
            parser_type="SSH_AUTH",
            is_synthetic=True,
            metadata_json={"campaign": "Simulated Privileged Anomaly", "synthetic": True}
        )
        events.append(ev_root)

        # Scenario 5: Windows Event 4625 / 4624 series
        win_ip = "192.168.10.45"
        for i in range(5):
            ts = now - timedelta(minutes=30) + timedelta(seconds=i * 10)
            ev = SecurityEvent(
                event_uuid=f"evt-demo-{uuid.uuid4().hex[:12]}",
                timestamp=ts,
                source_ip=win_ip,
                source_port=None,
                destination_ip="192.168.10.1",
                destination_port=445,
                event_type="WIN_EVENT_4625",
                action="LOGIN",
                status="FAILURE",
                username="Administrator",
                hostname="DC-CORP-01",
                service="Security",
                raw_log=f'{{"EventID": 4625, "TimeCreated": "{ts.isoformat()}", "TargetUserName": "Administrator", "IpAddress": "{win_ip}"}}',
                parser_type="WINDOWS_SECURITY",
                is_synthetic=True,
                metadata_json={"campaign": "Windows AD Audit", "synthetic": True}
            )
            events.append(ev)

        # Add all events
        db.add_all(events)
        db.commit()

        # Run detection engine to generate alerts on these synthetic events
        detector = DetectionEngine()
        alerts = detector.process_and_persist(db, events, is_synthetic=True)

        # Create a sample investigation linking the highest alert
        if alerts:
            top_alert = max(alerts, key=lambda a: 1 if a.severity == "CRITICAL" else 0)
            inv = Investigation(
                case_number=f"SEC-CASE-{datetime.utcnow().strftime('%Y%m')}-001",
                title="Investigation: Simulated Multi-Stage Authentication Campaign",
                description="Automated triage created for correlated synthetic brute-force and credential stuffing campaign.",
                severity=top_alert.severity,
                status="IN_PROGRESS",
                associated_alert_ids=[top_alert.alert_uuid],
                associated_ips=[top_alert.source_ip] if top_alert.source_ip else [],
                associated_users=[top_alert.target_username] if top_alert.target_username else [],
                verdict=None,
                summary="Initial triage shows high failure rates followed by anomalous access. Immediate containment in progress."
            )
            db.add(inv)
            db.commit()

        return {
            "status": "SUCCESS",
            "message": "Demo data generated successfully",
            "events_count": len(events),
            "alerts_count": len(alerts),
            "is_synthetic": True
        }

    @staticmethod
    def reset_demo_data(db: Session) -> Dict[str, Any]:
        """
        Safely deletes ONLY synthetic records. Production data is completely untouched.
        """
        deleted_alerts = db.query(Alert).filter(Alert.is_synthetic == True).delete(synchronize_session=False)
        deleted_events = db.query(SecurityEvent).filter(SecurityEvent.is_synthetic == True).delete(synchronize_session=False)
        db.commit()
        logger.info(f"Purged synthetic data: {deleted_events} events, {deleted_alerts} alerts")
        return {
            "status": "SUCCESS",
            "deleted_events": deleted_events,
            "deleted_alerts": deleted_alerts
        }
